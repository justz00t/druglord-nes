#!/usr/bin/env python3
"""Writes menu.h: the main-menu music ("boom bap", 90 BPM, C minor), played by menu_frame() in druglord.c.
One bar = 16 steps of 11/9 frames (swung 16ths at 90 BPM).  The bass, the chord stabs and the hook repeat every
4 bars (64 steps); the hook only plays in bars 5-8.  The drums repeat every 2 bars (32 steps)."""
import os
here = os.path.dirname(os.path.abspath(__file__)); out = os.path.dirname(here)
NOTE = {'C': 0, 'D': 2, 'E': 4, 'F': 5, 'G': 7, 'A': 9, 'B': 11}
def m(s):
    k = NOTE[s[0]]; i = 1
    while i < len(s) and s[i] in 'b#': k += -1 if s[i] == 'b' else 1; i += 1
    return k + 12 * (int(s[i:]) + 1)
prog = [['C4', 'Eb4', 'G4', 'Bb4'], ['C4', 'Eb4', 'G4', 'D5'], ['Ab3', 'C4', 'Eb4', 'G4'], ['G3', 'B3', 'D4', 'F4']]
bass = [[('C2', 0, 5), ('C2', 7, 2), ('Eb2', 10, 3), ('G1', 14, 2)],
        [('C2', 0, 5), ('C2', 7, 2), ('Bb1', 10, 4), ('C2', 15, 1)],
        [('Ab1', 0, 5), ('Ab1', 7, 2), ('Eb2', 10, 3), ('Ab1', 14, 2)],
        [('G1', 0, 5), ('G1', 7, 2), ('D2', 10, 2), ('F2', 12, 2), ('G2', 14, 2)]]
hook = [[('G5', 0, 3), ('Eb5', 3, 2), ('C5', 6, 2), ('D5', 8, 4), ('Bb4', 13, 3)],
        [('C5', 0, 6), ('G4', 8, 2), ('Bb4', 10, 2), ('C5', 12, 4)],
        [('Eb5', 0, 3), ('D5', 3, 2), ('C5', 6, 2), ('G4', 8, 6)],
        [('B4', 0, 4), ('D5', 4, 2), ('F5', 6, 2), ('G5', 8, 8)]]
bn = [0] * 64; bl = [0] * 64; st = [0] * 64; hn = [0] * 64; hl = [0] * 64
for b in range(4):
    for k, s, l in bass[b]: bn[b * 16 + s] = m(k); bl[b * 16 + s] = l
    for s in (0, 3, 10): st[b * 16 + s] = b + 1
    for k, s, l in hook[b]: hn[b * 16 + s] = m(k); hl[b * 16 + s] = l
# drums: bit 0 kick (noise + triangle thump), bit 1 kick (noise only), bit 2 snare, bits 4-6 hi-hat volume
dr = [0] * 32
for b in range(2):
    for s in (0, 7, 10): dr[b * 16 + s] |= 1
    if b: dr[b * 16 + 15] |= 2
    for s in (4, 12): dr[b * 16 + s] |= 4
    for s in range(0, 16, 2): dr[b * 16 + s] |= (5 if s % 4 else 3) << 4
    dr[b * 16 + 15] |= 2 << 4
chords = [[m(x) for x in c] for c in prog]
# pulse periods (CPU / (16 f) - 1) for MIDI notes LO..HI; the triangle uses (p + 1) / 2 - 1
LO, HI = 31, 84
per = [round(1789773 / (16 * 440 * 2 ** ((k - 69) / 12))) - 1 for k in range(LO, HI + 1)]
used = set(bn + hn + sum(chords, []) + [60, 50, 43, 38, 34]) - {0}
assert min(used) >= LO and max(used) <= HI
def arr(t, name, v): return 'static const %s %s[%d] = {%s};\n' % (t, name, len(v), ','.join(map(str, v)))
with open(os.path.join(out, 'menu.h'), 'w') as o:
    o.write('/* generated by tools/menu_song.py - do not edit */\n#define MN_LO %d\n' % LO)
    o.write(arr('u16', 'mn_per', per))
    for name, v in (('mn_bn', bn), ('mn_bl', bl), ('mn_st', st), ('mn_hn', hn), ('mn_hl', hl), ('mn_dr', dr), ('mn_ch', sum(chords, []))):
        o.write(arr('u8', name, v))
print('menu.h written')
