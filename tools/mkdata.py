#!/usr/bin/env python3
"""Builds chr.bin (font as 2bpp tiles) and music.h (title tune) from the sources in tools/."""
import struct, sys, os
here = os.path.dirname(os.path.abspath(__file__)); out = os.path.dirname(here)

# --- CHR: 256 CP437 glyphs, colour 1 on 0; tiles 0..255 for BG, same for sprites
f = open(os.path.join(here, 'font8x8.bin'), 'rb').read()
assert len(f) == 2048
chr_ = bytearray()
for t in range(256):
    g = f[t*8:t*8+8]
    chr_ += g + bytes(8)
chr_ = chr_ + chr_
open(os.path.join(out, 'chr.bin'), 'wb').write(chr_)

# --- MIDI -> per-16th-note step tables (10 frames per step at 90 bpm)
d = open(os.path.join(here, 'title.mid'), 'rb').read()
n, div = struct.unpack('>HH', d[10:14]); STEP = div // 4
p = 14; tracks = []
def vl(b, i):
    v = 0
    while True:
        c = b[i]; i += 1; v = (v << 7) | (c & 0x7f)
        if not c & 0x80: return v, i
for t in range(n):
    L = struct.unpack('>I', d[p+4:p+8])[0]; b = d[p+8:p+8+L]; p += 8+L
    i = tm = rs = 0; ons = []
    while i < len(b):
        dt, i = vl(b, i); tm += dt; s = b[i]
        if s == 0xff:
            l, j = vl(b, i+2); i = j+l; continue
        if s & 0x80: rs = s; i += 1
        if rs & 0xf0 in (0xc0, 0xd0): i += 1; continue
        if rs & 0xf0 == 0x90 and b[i+1]: ons.append((tm // STEP, b[i]))
        i += 2
    tracks.append(ons)
steps = max(s for tr in tracks for s, _ in tr) + 2
mel = [0]*steps; drm = [0]*steps
for s, k in tracks[0]: mel[s] = k
for s, k in tracks[1]: drm[s] = k
# pulse period = 1789773/(16*f)-1
def per(k): return round(1789773 / (16 * 440 * 2 ** ((k - 69) / 12))) - 1
notes = sorted(set(k for k in mel if k))
with open(os.path.join(out, 'music.h'), 'w') as o:
    o.write('/* generated by tools/mkdata.py from tools/title.mid - do not edit */\n')
    o.write('#define TUNE_STEPS %d\n' % steps)
    o.write('static const unsigned short note_period[] = {0, %s};\n' % ', '.join(str(per(k)) for k in notes))
    o.write('static const unsigned char tune_mel[TUNE_STEPS] = {%s};\n' % ','.join(str(notes.index(k)+1 if k else 0) for k in mel))
    dm = {0: 0, 42: 1, 39: 2, 38: 3}
    o.write('/* drums: 0 none, 1 hat, 2 clap, 3 snare */\n')
    o.write('static const unsigned char tune_drm[TUNE_STEPS] = {%s};\n' % ','.join(str(dm[k]) for k in drm))
print('steps', steps, 'notes', notes)
